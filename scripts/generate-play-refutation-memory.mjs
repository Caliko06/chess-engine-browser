#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";

const defaultInput = "data/engine-memory/refutations.v1.json";
const defaultOutput = "apps/web/src/generated/play-refutation-memory.generated.ts";

function parseArgs(argv) {
  const args = { input: defaultInput, output: defaultOutput };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--input") {
      args.input = argv[index + 1] ?? "";
      index += 1;
    } else if (arg === "--output") {
      args.output = argv[index + 1] ?? "";
      index += 1;
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  if (args.input === "") {
    throw new Error("--input requires a path");
  }
  if (args.output === "") {
    throw new Error("--output requires a path");
  }
  return args;
}

export function generatePlayRefutationMemoryModule(memory) {
  if (memory?.schema !== 1 || !Array.isArray(memory.cases)) {
    throw new Error("refutation memory must use schema 1 with cases[]");
  }
  const cases = memory.cases.map((entry) => {
    if (
      typeof entry?.positionKey !== "string" ||
      typeof entry.move !== "string" ||
      typeof entry.advice !== "string"
    ) {
      throw new Error("refutation memory case is missing positionKey, move, or advice");
    }
    return {
      positionKey: entry.positionKey,
      move: entry.move,
      advice: entry.advice
    };
  });
  return [
    "// Generated by scripts/generate-play-refutation-memory.mjs from data/engine-memory/refutations.v1.json.",
    "// Do not edit by hand.",
    'import type { PlayRefutationMemoryCase } from "../play-refutation-memory.js";',
    "",
    `export const generatedPlayRefutationMemoryCases: readonly PlayRefutationMemoryCase[] = ${JSON.stringify(cases, null, 2)};`,
    ""
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = parseArgs(process.argv.slice(2));
  const memory = JSON.parse(readFileSync(args.input, "utf8"));
  writeFileSync(args.output, generatePlayRefutationMemoryModule(memory));
  console.log(`play-refutation-memory=${args.output}`);
}
